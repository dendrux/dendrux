@pytest.mark.parametrize(("rig", "mode"), o.CELLS, ids=CELL_IDS)
def test_goldens_are_not_vacuous(rig, mode) -> None:
    if o.regen_enabled():
        return
    wire = o.read_golden("wire", o.cell_name(rig, mode))
    for scenario in o.REQUIRED_SCENARIOS:
        legs = wire[scenario]["legs"]
        assert legs and all(leg["sdk_calls"] for leg in legs), scenario
        for leg in legs:
            for call in leg["sdk_calls"]:
                assert call["payload"]["model"]
                assert call["payload_sha256"]
    for scenario in ("client_tool_pause_resume", "mixed_server_client_pause"):
        run, resume = wire[scenario]["outcomes"]
        assert run["result"]["status"] == "waiting_client_tool"
        assert run["result"]["pause_state"]["pending_tool_calls"]
        assert resume["result"]["status"] == "success"
    assert len(wire["replay_runs"]["legs"]) == 3
    assert len(wire["parallel_tools"]["legs"][0]["sdk_calls"]) == 2
    if mode == "stream":
        assert wire["plain"]["outcomes"][0]["events"][-1][0] == "run_completed"
        assert wire["plain"]["legs"][0]["provider_calls"][0]["stream_events"]
    # Vendor-specific cache contract is actually captured.
    first = wire["context_stable_dynamic"]["legs"][0]["sdk_calls"][0]["cache"]
    if rig.vendor == "anthropic":
        assert first["marker_count"] == 3  # system, stable head, rolling last message
    elif rig.openrouter and rig.openrouter_model.startswith("anthropic/"):
        assert first["extra_body_cache_control"] == {"type": "ephemeral"}
    elif rig.name == "openai_chat_compat":
        assert first["prompt_cache_key"] is None
    else:
        assert first["prompt_cache_key"] is not None or rig.openrouter


