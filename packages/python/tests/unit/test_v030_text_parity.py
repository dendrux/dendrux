def test_compare_wire_is_sensitive_to_marker_key_and_order_changes() -> None:
    if o.regen_enabled():
        pytest.skip("no goldens while regenerating")
    anthropic = o.read_golden("wire", "anthropic__batch")["context_stable_dynamic"]
    openai = o.read_golden("wire", "openai_chat__batch")["context_stable_dynamic"]
    assert o.compare_wire(anthropic, copy.deepcopy(anthropic)) is None

    no_marker = copy.deepcopy(anthropic)
    del no_marker["legs"][0]["sdk_calls"][0]["payload"]["system"][0]["cache_control"]
    assert o.compare_wire(anthropic, no_marker)

    ttl = copy.deepcopy(anthropic)
    ttl["legs"][0]["sdk_calls"][0]["payload"]["system"][0]["cache_control"]["ttl"] = "1h"
    assert o.compare_wire(anthropic, ttl)

    key = copy.deepcopy(openai)
    key["legs"][0]["sdk_calls"][0]["payload"]["prompt_cache_key"] = "dendrux:other"
    assert o.compare_wire(openai, key)

    reordered = copy.deepcopy(openai)
    payload = reordered["legs"][0]["sdk_calls"][0]["payload"]
    reordered["legs"][0]["sdk_calls"][0]["payload"] = dict(reversed(list(payload.items())))
    assert o.compare_wire(openai, reordered), "key order is part of the wire bytes"

    extra_field = copy.deepcopy(openai)
    extra_field["legs"][0]["sdk_calls"][0]["payload"]["messages"][1]["content"] = [
        {
            "type": "text",
            "text": extra_field["legs"][0]["sdk_calls"][0]["payload"]["messages"][1]["content"],
        }
    ]
    assert o.compare_wire(openai, extra_field), "str -> one-element parts array must be caught"


def test_compare_rows_allows_only_null_new_columns() -> None:
    golden = {t: [{"id": "<ulid:1>", "meta": {"a": 1}}] for t in o.ROW_TABLES}
    same = copy.deepcopy(golden)
    assert o.compare_rows(golden, same) is None

    new_null = copy.deepcopy(golden)
    new_null["react_traces"][0]["image_view"] = None
    assert o.compare_rows(golden, new_null) is None

    new_value = copy.deepcopy(golden)
    new_value["react_traces"][0]["image_view"] = {"v": 1}
    assert "new column" in (o.compare_rows(golden, new_value) or "")

    new_json_key = copy.deepcopy(golden)
    new_json_key["agent_runs"][0]["meta"]["parts"] = []
    assert o.compare_rows(golden, new_json_key)

    fewer = copy.deepcopy(golden)
    fewer["tool_calls"] = []
    assert o.compare_rows(golden, fewer)


def test_normalizer_rules() -> None:
    norm = o.Normalizer()
    ulid_a, ulid_b = "01M55DKFMCETP4XX2PG3DPJ8F9", "01M55DKFMCETP4XX2PG3DPJ8FA"
    out = norm(
        {
            "id": ulid_a,
            ulid_b: "tool call " + ulid_a,
            "created_at": "2026-01-01T00:00:00Z",
            "duration_ms": 12,
            "timestamp": 1,
            "cost": 0.123456789,
            "text": "a string that is 26 chars xx",
        }
    )
    assert out == {
        "id": "<ulid:1>",
        "<ulid:2>": "tool call <ulid:1>",
        "created_at": "<ts>",
        "duration_ms": "<ms>",
        "timestamp": "<ts>",
        "cost": 0.123457,
        "text": "a string that is 26 chars xx",
    }
    assert json.dumps(o.jsonable({"a": [1, {"b": None}]})) == '{"a": [1, {"b": null}]}'


def test_regeneration_is_opt_in_and_refuses_other_versions(monkeypatch) -> None:
    monkeypatch.delenv(o.REGEN_ENV, raising=False)
    assert o.regen_enabled() is False
    monkeypatch.setenv(o.REGEN_ENV, "1")
    monkeypatch.setattr(o, "package_version", lambda: "0.4.0")
    with pytest.raises(RuntimeError, match="never bless candidate output"):
        o.regen_enabled()
    monkeypatch.setenv(o.REGEN_ENV, "0")
    assert o.regen_enabled() is False
