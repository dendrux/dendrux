@pytest.mark.parametrize(("rig", "mode"), o.CELLS, ids=CELL_IDS)
async def test_text_only_wire_matches_v030(rig, mode, sqlite_engine) -> None:
    name = o.cell_name(rig, mode)
    result = await o.run_cell(rig, mode, sqlite_engine)
    if o.regen_enabled():
        o.write_golden("wire", name, result.wire)
        o.write_golden("rows", name, result.rows)
        return
    golden = o.read_golden("wire", name)
    assert list(golden) == list(result.wire), "scenario set/order changed"
    for scenario in golden:
        diff = o.compare_wire(golden[scenario], result.wire[scenario])
        assert diff is None, f"{name}/{scenario}: {diff}"
    assert o.dumps_ordered(golden) == o.dumps_ordered(result.wire)


