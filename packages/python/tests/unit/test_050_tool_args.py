        assert [tc.params["amount"] for tc in pending] == [1]
        assert hooked == [1]
        assert [e["call_id"] for e in rec.events("approval.requested")] == [calls[0].id]
        rejected = [r for _, r in rec.tools]
        assert len(rejected) == 2 and all(not r.success for r in rejected)
        assert all(r.meta["code"] == "max_calls" for r in rejected)

